function [result,windows,meta] = acycleDynamicFilter( ...
        data,lowerControlPoints,upperControlPoints,options)
%ACYCLEDYNAMICFILTER Deterministic coordinate-varying Gaussian band-pass.
%   [RESULT,WINDOWS,META] = ACYCLEDYNAMICFILTER(DATA,LOWER,UPPER,OPTIONS)
%   filters a finite real N-by-2 series [coordinate,value] with an explicit
%   coordinate-varying passband. DATA must already be strictly increasing
%   and regularly sampled to the fixed relative spacing tolerance 1e-5;
%   rows are never sorted, merged, removed, or interpolated.
%
%   LOWER and UPPER are finite K-by-2 floating-point matrices whose columns
%   are [coordinate,frequency]. Each coordinate vector must be strictly
%   increasing and lie inside the DATA domain. A one-row control is
%   constant. Otherwise each path is linearly interpolated between control
%   points and held constant beyond its first and last point. The complete
%   piecewise-linear paths must satisfy
%       0 < lower_frequency < upper_frequency < physical_Nyquist.
%
%   OPTIONS is a scalar structure containing exactly these required fields:
%     window_length  positive first-to-last window span in coordinate units
%     step_length    positive displacement between successive window starts
%
%   Physical lengths are divided by MEDIAN(DIFF(DATA(:,1))) and rounded to
%   the nearest sampling interval (positive half ties away from zero).
%   WINDOW_LENGTH then gains one endpoint sample and must contain at least
%   eight samples. STEP_LENGTH must resolve to at least one sample and may
%   not exceed the window sample count, so no coverage gaps are possible.
%   A terminal window ending on the final sample is appended when the
%   regular start grid would otherwise leave an uncovered tail.
%
%   Each window is locally mean-centred, multiplied by the square root of a
%   strictly-positive half-sample-shifted Hann weight, Gaussian filtered in
%   an explicitly zero-padded FFT, multiplied by the same synthesis weight,
%   and overlap-added. The Gaussian lower and upper frequencies are exact
%   half-power (-3 dB) points. The output is divided by the sum of synthesis
%   weights, never by the count of nonzero filtered values.
%
%   RESULT columns are [coordinate,filtered_value,coverage_count,
%   coverage_weight]. WINDOWS columns are [window_center,lower_frequency,
%   upper_frequency,center_frequency,window_start_coordinate,
%   window_end_coordinate,window_start_index,window_end_index]. No files,
%   graphics, dialogs, current-folder/path changes, workspace assignment,
%   or random-number generation occur.
%
%   Algorithm lineage: dynamic filtering by Nicolas Thibault and Giovanni
%   Rizzi (2019), adapted for Acycle Frequency Stabilization by Mingsong Li
%   (June 2020).

narginchk(4,4);
limits = resourceLimits();
contract = validateSeries(data,limits);
options = validateOptions(options);

working = full(double(data));
coordinates = working(:,1);
values = working(:,2);
inputRows = size(working,1);
coordinateStart = coordinates(1);
coordinateEnd = coordinates(end);
coordinateSpan = coordinateEnd-coordinateStart;
nyquist = contract.physical_nyquist;

lowerControlPoints = validateControlPoints( ...
    lowerControlPoints,'lower',coordinateStart,coordinateEnd,limits);
upperControlPoints = validateControlPoints( ...
    upperControlPoints,'upper',coordinateStart,coordinateEnd,limits);
[pathCheckCoordinates,pathCheckLower,pathCheckUpper] = validatePassbandPaths( ...
    lowerControlPoints,upperControlPoints,coordinateStart,coordinateEnd, ...
    nyquist);

[windowIntervals,windowSamples,effectiveWindowLength,windowRatio] = ...
    resolveWindow(options.window_length,contract.sample_interval, ...
    coordinateSpan,inputRows);
[stepSamples,effectiveStepLength,stepRatio] = resolveStep( ...
    options.step_length,contract.sample_interval,windowSamples);

lastStart = inputRows-windowSamples+1;
startIndices = (1:stepSamples:lastStart)';
terminalWindowAppended = startIndices(end) ~= lastStart;
if terminalWindowAppended
    startIndices(end+1,1) = lastStart;
end
endIndices = startIndices+windowSamples-1;
windowCenters = coordinates(startIndices)+ ...
    (coordinates(endIndices)-coordinates(startIndices))/2;
windowCount = numel(startIndices);
if windowCount > limits.maximum_window_count
    error('Acycle:DynamicFilter:WindowCountLimitExceeded', ...
        ['The request produces %d windows; the fixed maximum is %d. ', ...
         'Increase STEP_LENGTH or shorten the input.'], ...
        windowCount,limits.maximum_window_count);
end

lowerFrequency = interpolateClamped( ...
    lowerControlPoints,windowCenters);
upperFrequency = interpolateClamped( ...
    upperControlPoints,windowCenters);
centerFrequency = lowerFrequency+(upperFrequency-lowerFrequency)/2;
if any(~isfinite(centerFrequency))
    error('Acycle:DynamicFilter:UnrepresentableCenterFrequency', ...
        'A passband center is not representable as finite DOUBLE.');
end

minimumFftLength = 2*windowSamples-1;
fftLength = 2^nextpow2(minimumFftLength);
if ~(isfinite(fftLength) && fftLength >= minimumFftLength && ...
        fftLength == fix(fftLength) && mod(fftLength,2) == 0)
    error('Acycle:DynamicFilter:InvalidFftLength', ...
        'The deterministic FFT length is invalid.');
end
if fftLength > limits.maximum_fft_length
    error('Acycle:DynamicFilter:FFTLengthLimitExceeded', ...
        ['The effective window requires FFT length %d; the fixed ', ...
         'maximum is %d.'],fftLength,limits.maximum_fft_length);
end
frequencyResolution = 1/(fftLength*contract.sample_interval);
passbandWidth = upperFrequency-lowerFrequency;
resolutionTolerance = 64*eps(max(1,frequencyResolution));
if any(passbandWidth < frequencyResolution-resolutionTolerance)
    first = find(passbandWidth < ...
        frequencyResolution-resolutionTolerance,1,'first');
    error('Acycle:DynamicFilter:PassbandBelowFrequencyResolution', ...
        ['Window %d has passband width %.17g, below the deterministic ', ...
         'FFT resolution %.17g. Increase WINDOW_LENGTH or widen the ', ...
         'passband.'],first,passbandWidth(first),frequencyResolution);
end

outputElements = double(inputRows)*4+double(windowCount)*8;
if ~isfinite(outputElements) || ...
        outputElements > limits.maximum_output_elements
    error('Acycle:DynamicFilter:OutputElementLimitExceeded', ...
        ['RESULT and WINDOWS would contain %.17g values; the fixed ', ...
         'maximum is %.17g.'],outputElements,limits.maximum_output_elements);
end
fftWorkUnits = double(windowCount)*double(fftLength)* ...
    max(1,ceil(log2(double(fftLength))));
if ~isfinite(fftWorkUnits) || ...
        fftWorkUnits > limits.maximum_fft_work_units
    error('Acycle:DynamicFilter:FFTWorkLimitExceeded', ...
        ['The request requires %.17g fixed FFT work units; the maximum ', ...
         'is %.17g. Increase STEP_LENGTH or reduce WINDOW_LENGTH.'], ...
        fftWorkUnits,limits.maximum_fft_work_units);
end

valueScale = max(abs(values));
if valueScale == 0
    scaledValues = zeros(inputRows,1);
else
    scaledValues = values/valueScale;
end
weight = halfSampleShiftedHann(windowSamples);
analysisWeight = sqrt(weight);
coverageWeight = zeros(inputRows,1);
coverageCount = zeros(inputRows,1);
filteredAccumulator = zeros(inputRows,1);
absoluteBin = min((0:fftLength-1)',(fftLength:-1:1)');
absoluteFrequency = absoluteBin*frequencyResolution;
maximumImaginaryResidual = 0;
maximumImaginaryTolerance = 0;
minimumPeakResponse = Inf;
maximumPeakResponse = 0;

for windowIndex = 1:windowCount
    indices = startIndices(windowIndex):endIndices(windowIndex);
    segment = scaledValues(indices);
    localMean = mean(segment);
    centeredSegment = segment-localMean;
    if any(~isfinite(centeredSegment))
        error('Acycle:DynamicFilter:UnrepresentableCentering', ...
            'Local mean centering failed in window %d.',windowIndex);
    end

    halfBandwidth = passbandWidth(windowIndex)/2;
    normalizedOffset = ...
        (absoluteFrequency-centerFrequency(windowIndex))/halfBandwidth;
    response = exp(-log(sqrt(2))*normalizedOffset.^2);
    if any(~isfinite(response)) || any(response < 0) || any(response > 1)
        error('Acycle:DynamicFilter:InvalidFrequencyResponse', ...
            'Window %d produced an invalid Gaussian response.',windowIndex);
    end
    oneSidedPeak = max(response(1:fftLength/2+1));
    minimumPeakResponse = min(minimumPeakResponse,oneSidedPeak);
    maximumPeakResponse = max(maximumPeakResponse,oneSidedPeak);

    coefficients = fft(centeredSegment.*analysisWeight,fftLength);
    timeDomain = ifft(coefficients.*response);
    imaginaryResidual = max(abs(imag(timeDomain)));
    imaginaryTolerance = 2048*eps(max(1,max(abs(timeDomain))));
    maximumImaginaryResidual = max( ...
        maximumImaginaryResidual,imaginaryResidual);
    maximumImaginaryTolerance = max( ...
        maximumImaginaryTolerance,imaginaryTolerance);
    if imaginaryResidual > imaginaryTolerance
        error('Acycle:DynamicFilter:NonHermitianFilterResult', ...
            ['Window %d inverse FFT has imaginary residual %.17g, ', ...
             'above tolerance %.17g.'], ...
            windowIndex,imaginaryResidual,imaginaryTolerance);
    end
    localFiltered = real(timeDomain(1:windowSamples)).*analysisWeight;
    if any(~isfinite(localFiltered))
        error('Acycle:DynamicFilter:NonfiniteWindowOutput', ...
            'Window %d produced a nonfinite filtered value.',windowIndex);
    end
    filteredAccumulator(indices) = ...
        filteredAccumulator(indices)+localFiltered;
    coverageWeight(indices) = coverageWeight(indices)+weight;
    coverageCount(indices) = coverageCount(indices)+1;
end

if any(~isfinite(coverageWeight)) || any(coverageWeight <= 0) || ...
        any(coverageCount < 1)
    error('Acycle:DynamicFilter:IncompleteCoverage', ...
        ['The deterministic window schedule failed to cover every ', ...
         'input sample with positive synthesis weight.']);
end
filteredNormalized = filteredAccumulator./coverageWeight;
if valueScale == 0
    filtered = zeros(inputRows,1);
else
    filtered = filteredNormalized*valueScale;
end
if any(~isfinite(filtered))
    error('Acycle:DynamicFilter:NonfiniteOutput', ...
        ['The filtered result is not representable as finite DOUBLE. ', ...
         'Rescale extreme input values.']);
end

result = [coordinates,filtered,coverageCount,coverageWeight];
windows = [windowCenters,lowerFrequency,upperFrequency,centerFrequency, ...
    coordinates(startIndices),coordinates(endIndices), ...
    double(startIndices),double(endIndices)];
if ~isequal(size(result),[inputRows,4]) || ...
        ~isequal(size(windows),[windowCount,8]) || ...
        any(~isfinite(result(:))) || any(~isfinite(windows(:)))
    error('Acycle:DynamicFilter:InvalidOutput', ...
        'Dynamic filtering produced an invalid output matrix.');
end

if windowCount > 1
    startSteps = diff(startIndices);
    minimumStartStepSamples = min(startSteps);
    maximumStartStepSamples = max(startSteps);
else
    minimumStartStepSamples = NaN;
    maximumStartStepSamples = NaN;
end
warningIds = cell(0,1);
warningMessages = cell(0,1);
if contract.spacing_departure_above_roundoff
    warningIds{end+1,1} = ...
        'Acycle:DynamicFilter:SpacingDepartureWithinTolerance';
    warningMessages{end+1,1} = sprintf( ...
        ['Coordinate spacing departure %.17g exceeds roundoff but ', ...
         'remains within the accepted relative tolerance %.17g. No ', ...
         'interpolation was performed.'], ...
        contract.maximum_spacing_error,contract.spacing_tolerance);
end

