function contract = validateSeries(data,limits)
if ~((isa(data,'double') || isa(data,'single')) && ...
        ~issparse(data) && isreal(data) && ismatrix(data) && ...
        size(data,2) == 2)
    error('Acycle:DynamicFilter:InvalidData', ...
        ['DATA must be a full real SINGLE or DOUBLE N-by-2 matrix ', ...
         '[coordinate,value].']);
end
inputRows = size(data,1);
if inputRows < 8
    error('Acycle:DynamicFilter:TooFewRows', ...
        'Dynamic filtering requires at least eight input rows.');
end
if inputRows > limits.maximum_input_rows
    error('Acycle:DynamicFilter:InputRowLimitExceeded', ...
        'DATA exceeds the fixed maximum of %d rows.', ...
        limits.maximum_input_rows);
end
if any(~isfinite(data(:)))
    error('Acycle:DynamicFilter:NonfiniteData', ...
        'Every DATA coordinate and value must be finite.');
end
coordinates = double(data(:,1));
spacing = diff(coordinates);
if any(~isfinite(spacing))
    error('Acycle:DynamicFilter:UnrepresentableSpacing', ...
        'Every coordinate spacing must be representable as finite DOUBLE.');
end
if any(spacing <= 0)
    error('Acycle:DynamicFilter:CoordinatesNotStrictlyIncreasing', ...
        ['DATA coordinates must already be sorted, unique, and strictly ', ...
         'increasing.']);
end
sampleInterval = median(spacing);
maximumSpacingError = max(abs(spacing-sampleInterval));
relativeSpacingDeparture = maximumSpacingError/sampleInterval;
spacingTolerance = 1e-5;
if ~(isfinite(sampleInterval) && sampleInterval > 0 && ...
        isfinite(relativeSpacingDeparture)) || ...
        relativeSpacingDeparture > spacingTolerance
    error('Acycle:DynamicFilter:UnevenSampling', ...
        ['Relative spacing departure %.17g exceeds the fixed tolerance ', ...
         '%.17g. Interpolate explicitly before dynamic filtering.'], ...
        relativeSpacingDeparture,spacingTolerance);
end
coordinateScale = max([1;abs(coordinates);abs(sampleInterval)]);
roundoffTolerance = 128*eps(coordinateScale);
physicalNyquist = 1/(2*sampleInterval);
if ~(isfinite(physicalNyquist) && physicalNyquist > 0)
    error('Acycle:DynamicFilter:InvalidNyquist', ...
        'The physical Nyquist frequency must be finite and positive.');
end
contract = struct( ...
    'sample_interval',sampleInterval, ...
    'maximum_spacing_error',maximumSpacingError, ...
    'relative_spacing_departure',relativeSpacingDeparture, ...
    'spacing_tolerance',spacingTolerance, ...
    'roundoff_absolute_tolerance',roundoffTolerance, ...
    'spacing_departure_above_roundoff', ...
        maximumSpacingError > roundoffTolerance, ...
    'physical_nyquist',physicalNyquist);
end

function options = validateOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error('Acycle:DynamicFilter:InvalidOptions', ...
        'OPTIONS must be a scalar structure.');
end
allowed = {'window_length','step_length'};
unknown = setdiff(fieldnames(options),allowed);
if ~isempty(unknown)
    error('Acycle:DynamicFilter:UnknownOption', ...
        'Unknown dynamic-filter option: %s.',unknown{1});
end
for index = 1:numel(allowed)
    name = allowed{index};
    if ~isfield(options,name) || isempty(options.(name))
        error('Acycle:DynamicFilter:MissingOption', ...
            'Required option %s is missing.',upper(name));
    end
    options.(name) = positiveFiniteScalar(options.(name),name);
end
end

function points = validateControlPoints( ...
        points,name,coordinateStart,coordinateEnd,limits)
if ~((isa(points,'double') || isa(points,'single')) && ...
        ~issparse(points) && isreal(points) && ismatrix(points) && ...
        size(points,2) == 2)
    error('Acycle:DynamicFilter:InvalidControlPoints', ...
        ['%s control points must be a full real SINGLE or DOUBLE ', ...
         'K-by-2 matrix [coordinate,frequency].'],upper(name));
end
if isempty(points)
    error('Acycle:DynamicFilter:EmptyControlPoints', ...
        '%s control points must contain at least one row.',upper(name));
end
if size(points,1) > limits.maximum_control_points
    error('Acycle:DynamicFilter:ControlPointLimitExceeded', ...
        '%s control points exceed the fixed maximum of %d rows.', ...
        upper(name),limits.maximum_control_points);
end
if any(~isfinite(points(:)))
    error('Acycle:DynamicFilter:NonfiniteControlPoints', ...
        'Every %s control coordinate and frequency must be finite.',name);
end
points = full(double(points));
if size(points,1) > 1 && any(diff(points(:,1)) <= 0)
    error('Acycle:DynamicFilter:ControlCoordinatesNotStrictlyIncreasing', ...
        ['%s control coordinates must already be sorted, unique, and ', ...
         'strictly increasing.'],upper(name));
end
if any(points(:,1) < coordinateStart) || ...
        any(points(:,1) > coordinateEnd)
    error('Acycle:DynamicFilter:ControlCoordinateOutsideData', ...
        ['Every %s control coordinate must lie inside the DATA ', ...
         'coordinate domain [%.17g, %.17g].'], ...
        upper(name),coordinateStart,coordinateEnd);
end
if any(points(:,2) <= 0)
    error('Acycle:DynamicFilter:NonpositiveControlFrequency', ...
        'Every %s control frequency must be strictly positive.',upper(name));
end
end

function [coordinates,lower,upper] = validatePassbandPaths( ...
        lowerPoints,upperPoints,coordinateStart,coordinateEnd,nyquist)
coordinates = unique([coordinateStart;lowerPoints(:,1); ...
    upperPoints(:,1);coordinateEnd]);
lower = interpolateClamped(lowerPoints,coordinates);
upper = interpolateClamped(upperPoints,coordinates);
if any(upper >= nyquist)
    first = find(upper >= nyquist,1,'first');
    error('Acycle:DynamicFilter:FrequencyAtOrAboveNyquist', ...
        ['Upper passband frequency %.17g at coordinate %.17g must be ', ...
         'strictly below the physical Nyquist frequency %.17g.'], ...
        upper(first),coordinates(first),nyquist);
end
if any(lower >= upper)
    first = find(lower >= upper,1,'first');
    error('Acycle:DynamicFilter:InvalidPassbandOrder', ...
        ['Passband paths must satisfy LOWER < UPPER. At coordinate ', ...
         '%.17g they are %.17g and %.17g.'], ...
        coordinates(first),lower(first),upper(first));
end
end

function values = interpolateClamped(points,query)
if size(points,1) == 1
    values = repmat(points(1,2),size(query));
    return
end
values = interp1(points(:,1),points(:,2),query,'linear');
values(query < points(1,1)) = points(1,2);
values(query > points(end,1)) = points(end,2);
if any(~isfinite(values))
    error('Acycle:DynamicFilter:ControlInterpolationFailed', ...
        'Passband control interpolation produced a nonfinite value.');
end
end

function [intervals,samples,effective,ratio] = resolveWindow( ...
        requested,dt,span,inputRows)
if requested > span
    error('Acycle:DynamicFilter:WindowLongerThanSpan', ...
        'WINDOW_LENGTH %.17g exceeds the DATA coordinate span %.17g.', ...
        requested,span);
end
ratio = requested/dt;
intervals = roundPositiveHalfAway(ratio);
samples = intervals+1;
if samples < 8
    error('Acycle:DynamicFilter:WindowTooShort', ...
        ['WINDOW_LENGTH resolves to %d samples; dynamic filtering ', ...
         'requires at least eight.'],samples);
end
if samples > inputRows
    error('Acycle:DynamicFilter:WindowSampleCountTooLarge', ...
        ['WINDOW_LENGTH resolves to %d samples, exceeding the %d ', ...
         'input rows.'],samples,inputRows);
end
effective = intervals*dt;
if ~(isfinite(effective) && effective > 0)
    error('Acycle:DynamicFilter:InvalidEffectiveWindow', ...
        'The effective window length must be finite and positive.');
end
end

function [samples,effective,ratio] = resolveStep(requested,dt,windowSamples)
ratio = requested/dt;
samples = roundPositiveHalfAway(ratio);
if samples < 1
    error('Acycle:DynamicFilter:StepTooShort', ...
        ['STEP_LENGTH resolves to zero samples. Increase it to at least ', ...
         'half the sample interval.']);
end
if samples > windowSamples
    error('Acycle:DynamicFilter:StepCreatesCoverageGaps', ...
        ['STEP_LENGTH resolves to %d samples, greater than the %d-sample ', ...
         'window. This would create uncovered output samples.'], ...
        samples,windowSamples);
end
effective = samples*dt;
if ~(isfinite(effective) && effective > 0)
    error('Acycle:DynamicFilter:InvalidEffectiveStep', ...
        'The effective step length must be finite and positive.');
end
end

function rounded = roundPositiveHalfAway(value)
if ~(isfinite(value) && value >= 0)
    error('Acycle:DynamicFilter:InvalidLengthRatio', ...
        'A physical length/sample-interval ratio is invalid.');
end
rounded = floor(value+0.5);
end

function value = positiveFiniteScalar(value,name)
if ~(isnumeric(value) && ~islogical(value) && isreal(value) && ...
        isscalar(value) && isfinite(value) && value > 0)
    error('Acycle:DynamicFilter:InvalidNumericOption', ...
        '%s must be a finite positive real numeric scalar.',upper(name));
end
value = double(value);
end

function weight = halfSampleShiftedHann(samples)
phase = ((0:samples-1)'+0.5)/samples;
weight = 0.5-0.5*cos(2*pi*phase);
if any(~isfinite(weight)) || any(weight <= 0) || any(weight > 1)
    error('Acycle:DynamicFilter:InvalidOverlapWindow', ...
        'The deterministic overlap-add window is invalid.');
end
end
