end

function [files,qa] = saveOverviewResult(result,outputDirectory,stem)
[fig,handles] = bispectralPlot(result,'Visible','off','Quantity','overview', ...
    'ShowPeriodAxes',true,'PeakCount',5);
cleanup = onCleanup(@()closeFigure(fig));
drawnow;
qa = validateOverviewFigure(fig,handles,result);
result.ExternalPreprocessing.OverviewValidation = qa;
files = bispectralSave(result,fig,outputDirectory,[stem,'_overview']);
end

function qa = validateOverviewFigure(fig,handles,result)
required = {'PowerLeft','PowerRight','Bispectrum','Bicoherence', ...
    'BispectrumMap','BicoherenceMap','PowerSpectrumMetadata'};
if ~all(isfield(handles,required))
    error('Acycle:BispectralValidation:OverviewHandles', ...
        'The Overview figure did not return its required axes and maps.');
end
leftPowerBox = actualPlotBox(handles.PowerLeft);
rightPowerBox = actualPlotBox(handles.PowerRight);
leftMapBox = actualPlotBox(handles.Bispectrum);
rightMapBox = actualPlotBox(handles.Bicoherence);
tolerancePixels = 2.5;
leftAligned = max(abs(leftPowerBox([1 3])-leftMapBox([1 3]))) <= tolerancePixels;
rightAligned = max(abs(rightPowerBox([1 3])-rightMapBox([1 3]))) <= tolerancePixels;
leftMapSquare = abs(leftMapBox(3)-leftMapBox(4)) <= tolerancePixels;
rightMapSquare = abs(rightMapBox(3)-rightMapBox(4)) <= tolerancePixels;
leftXAligned = max(abs(handles.PowerLeft.XLim-handles.Bispectrum.XLim)) <= ...
    64*eps(max(1,max(abs(handles.Bispectrum.XLim))));
rightXAligned = max(abs(handles.PowerRight.XLim-handles.Bicoherence.XLim)) <= ...
    64*eps(max(1,max(abs(handles.Bicoherence.XLim))));
twoLogAxes = strcmp(handles.PowerLeft.YScale,'log') && ...
    strcmp(handles.PowerRight.YScale,'log');
leftAlpha = handles.BispectrumMap.Image.AlphaData;
rightAlpha = handles.BicoherenceMap.Image.AlphaData;
independentMasksVisible = nnz(leftAlpha > 0) > 0 && nnz(rightAlpha > 0) > 0 && ...
    isfinite(handles.BispectrumMap.KeepCutoff) && ...
    isfinite(handles.BicoherenceMap.KeepCutoff);
renderSettings = getappdata(fig,'BispectralRenderSettings');
hasIndependentSettings = isstruct(renderSettings) && ...
    isfield(renderSettings,'BispectrumKeepStrongestFraction') && ...
    isfield(renderSettings,'BicoherenceKeepStrongestFraction');
interpolatedPcolor = strcmp(handles.BispectrumMap.Image.FaceColor,'interp') && ...
    strcmp(handles.BicoherenceMap.Image.FaceColor,'interp') && ...
    strcmp(handles.BispectrumMap.Image.EdgeColor,'none') && ...
    strcmp(handles.BicoherenceMap.Image.EdgeColor,'none');
valueContoursPresent = isgraphics(handles.BispectrumMap.ValueContour) && ...
    isgraphics(handles.BicoherenceMap.ValueContour);
colorGridRecordedAndApplied = hasIndependentSettings && ...
    isfield(renderSettings,'ColorGrid') && ...
    size(colormap(handles.Bispectrum),1) == renderSettings.ColorGrid && ...
    size(colormap(handles.Bicoherence),1) == renderSettings.ColorGrid;

[powerCurvesPresent,powerCurvesIdentical,powerCurvesMatchMTM, ...
    powerCurvePointCount] = validatePowerCurves(handles,result);
[mtmMetadataRecorded,mtmRenderSettingsConsistent] = ...
    validateMtmMetadata(handles.PowerSpectrumMetadata,renderSettings,result);
[powerScaleCorrect,powerTicksLabeled] = validatePowerDisplay(handles);
powerTitlesCorrect = strcmp(handles.PowerLeft.Title.String, ...
    'Complex bispectrum amplitude, |B|') && ...
    strcmp(handles.PowerRight.Title.String, ...
    'Magnitude-squared bicoherence, b^2');
powerLabelsCorrect = isempty(strtrim(handles.PowerLeft.XLabel.String)) && ...
    isempty(strtrim(handles.PowerRight.XLabel.String)) && ...
    strcmp(handles.PowerLeft.YLabel.String,'2\pi MTM power') && ...
    strcmp(handles.PowerRight.YLabel.String,'2\pi MTM power');
mapTitlesEmpty = isempty(strtrim(handles.Bispectrum.Title.String)) && ...
    isempty(strtrim(handles.Bicoherence.Title.String));
mapLabelsPresent = contains(handles.Bispectrum.XLabel.String,'f_1') && ...
    contains(handles.Bispectrum.YLabel.String,'f_2') && ...
    contains(handles.Bicoherence.XLabel.String,'f_1') && ...
    contains(handles.Bicoherence.YLabel.String,'f_2');
[horizontalColorbars,colorbarsBetweenMapsAndCaption,colorbarBoxes] = ...
    validateOverviewColorbars(fig,handles,leftMapBox,rightMapBox);
[figureTitleCorrect,figureTitleExtensionFree] = ...
    validateOverviewTitle(fig,renderSettings,result);
[retainSettingsConsistent,retainCutoffsConsistent,expectedCutoffs] = ...
    validateOverviewRetain(result,handles,renderSettings);

qa = struct( ...
    'TwoLogPowerAxes',twoLogAxes, ...
    'TwoPowerCurvesPresent',powerCurvesPresent, ...
    'PowerCurvesIdentical',powerCurvesIdentical, ...
    'PowerCurvesMatchMTM',powerCurvesMatchMTM, ...
    'PowerCurvePointCount',powerCurvePointCount, ...
    'MTMMetadataRecorded',mtmMetadataRecorded, ...
    'MTMRenderSettingsConsistent',mtmRenderSettingsConsistent, ...
    'PowerScaleVisibleRangeAndHeadroomCorrect',powerScaleCorrect, ...
    'PowerYTicksLabeled',powerTicksLabeled, ...
    'PowerSpectrumMetadata',handles.PowerSpectrumMetadata, ...
    'PowerTitlesCorrect',powerTitlesCorrect, ...
    'PowerAndMapLabelsCorrect',powerLabelsCorrect && mapLabelsPresent, ...
    'MapTitlesEmpty',mapTitlesEmpty, ...
    'LeftActualPlotBoxAligned',leftAligned, ...
    'RightActualPlotBoxAligned',rightAligned, ...
    'LeftFrequencyLimitsAligned',leftXAligned, ...
    'RightFrequencyLimitsAligned',rightXAligned, ...
    'LeftMapActualPlotBoxSquare',leftMapSquare, ...
    'RightMapActualPlotBoxSquare',rightMapSquare, ...
    'IndependentMasksVisible',independentMasksVisible, ...
    'IndependentRetainSettingsRecorded',hasIndependentSettings, ...
    'RetainSettingsConsistent',retainSettingsConsistent, ...
    'RetainCutoffsConsistent',retainCutoffsConsistent, ...
    'ExpectedRetainCutoffs',expectedCutoffs, ...
    'ActualRetainCutoffs',[handles.BispectrumMap.KeepCutoff, ...
        handles.BicoherenceMap.KeepCutoff], ...
    'InterpolatedPcolorWithoutEdges',interpolatedPcolor, ...
    'ValueContoursPresent',valueContoursPresent, ...
    'ColorGridRecordedAndApplied',colorGridRecordedAndApplied, ...
    'HorizontalColorbars',horizontalColorbars, ...
    'ColorbarsBetweenMapsAndCaption',colorbarsBetweenMapsAndCaption, ...
    'ColorbarBoxesPixels',colorbarBoxes, ...
    'FigureTitleCorrect',figureTitleCorrect, ...
    'FigureTitleExtensionFree',figureTitleExtensionFree, ...
    'PlotBoxTolerancePixels',tolerancePixels, ...
    'LeftPowerPlotBoxPixels',leftPowerBox, ...
    'LeftMapPlotBoxPixels',leftMapBox, ...
    'RightPowerPlotBoxPixels',rightPowerBox, ...
    'RightMapPlotBoxPixels',rightMapBox);
checks = [twoLogAxes,leftAligned,rightAligned,leftXAligned,rightXAligned, ...
    leftMapSquare,rightMapSquare,independentMasksVisible, ...
    hasIndependentSettings,interpolatedPcolor,valueContoursPresent, ...
    colorGridRecordedAndApplied,powerCurvesPresent,powerCurvesIdentical, ...
    powerCurvesMatchMTM,mtmMetadataRecorded,mtmRenderSettingsConsistent, ...
    powerScaleCorrect,powerTicksLabeled, ...
    powerTitlesCorrect,powerLabelsCorrect,mapTitlesEmpty,mapLabelsPresent, ...
    horizontalColorbars,colorbarsBetweenMapsAndCaption,figureTitleCorrect, ...
    figureTitleExtensionFree,retainSettingsConsistent,retainCutoffsConsistent];
if ~all(checks)
    error('Acycle:BispectralValidation:OverviewLayout', ...
        ['An Overview failed its MTM curve/metadata, title/label, square ', ...
        'plot-box, frequency, pcolor, contour, colorbar, colormap, or ', ...
        'independent-retain QA.']);
end
end

function [scaleCorrect,ticksLabeled] = validatePowerDisplay(handles)
axesToCheck = [handles.PowerLeft handles.PowerRight];
scaleCorrect = true;
ticksLabeled = true;
for axisIndex = 1:numel(axesToCheck)
    ax = axesToCheck(axisIndex);
    lines = findobj(ax,'Type','line');
    if ~isscalar(lines)
        scaleCorrect = false;
        ticksLabeled = false;
        continue
    end
    frequency = double(lines.XData(:));
    power = double(lines.YData(:));
    visible = isfinite(frequency) & frequency >= ax.XLim(1) & ...
        frequency <= ax.XLim(2) & isfinite(power) & power > 0;
    if ~any(visible)
        scaleCorrect = false;
    else
        lower = min(power(visible));
        peak = max(power(visible));
        limits = ax.YLim;
        tolerance = 256*eps(max([1 abs(lower) abs(limits)]));
        if peak > lower*(1+64*eps)
            peakHeight = (log(peak)-log(limits(1)))/ ...
                (log(limits(2))-log(limits(1)));
            headroomCorrect = abs(peakHeight-0.8) <= 1e-10;
        else
            headroomCorrect = limits(2) > limits(1);
        end
        scaleCorrect = scaleCorrect && ...
            abs(limits(1)-lower) <= tolerance && headroomCorrect;
    end
    labels = ax.YTickLabel;
    if ischar(labels)
        labels = string(cellstr(labels));
    else
        labels = string(labels(:));
    end
    ticksLabeled = ticksLabeled && numel(ax.YTick) >= 3 && ...
        numel(labels) >= 3 && all(strlength(strtrim(labels)) > 0);
end
scaleCorrect = scaleCorrect && numericVectorsClose( ...
    handles.PowerLeft.YLim,handles.PowerRight.YLim);
end

function [present,identical,matchesExpected,pointCount] = ...
        validatePowerCurves(handles,result)
leftLines = findobj(handles.PowerLeft,'Type','line');
rightLines = findobj(handles.PowerRight,'Type','line');
present = isscalar(leftLines) && isscalar(rightLines);
identical = false;
matchesExpected = false;
pointCount = 0;
if ~present
    return
end
leftFrequency = double(leftLines(1).XData(:));
leftPower = double(leftLines(1).YData(:));
rightFrequency = double(rightLines(1).XData(:));
rightPower = double(rightLines(1).YData(:));
pointCount = numel(leftFrequency);
identical = numericVectorsClose(leftFrequency,rightFrequency) && ...
    numericVectorsClose(leftPower,rightPower);

y = double(result.ProcessedData(:,2));
y = y-mean(y);
nfft = 5*numel(y);
[expectedPower,angularFrequency] = pmtm(y,2,nfft);
expectedFrequency = double(angularFrequency(:))/(2*pi*result.Meta.SampleInterval);
expectedPower = double(expectedPower(:));
expectedPower(~isfinite(expectedPower) | expectedPower <= 0) = NaN;
matchesExpected = numericVectorsClose(leftFrequency,expectedFrequency) && ...
    numericVectorsClose(leftPower,expectedPower);
end

function [metadataRecorded,renderSettingsConsistent] = ...
        validateMtmMetadata(metadata,renderSettings,result)
requiredMetadata = {'Method','TimeBandwidth','TaperCount','PaddingFactor', ...
    'NFFT','InputLength','MeanRemoved','FrequencyCoordinate'};
metadataRecorded = isstruct(metadata) && isscalar(metadata) && ...
    all(isfield(metadata,requiredMetadata));
if metadataRecorded
    n = size(result.ProcessedData,1);
    metadataRecorded = strcmp(metadata.Method,'2pi MTM (Thomson)') && ...
        metadata.TimeBandwidth == 2 && metadata.TaperCount == 3 && ...
        metadata.PaddingFactor == 5 && metadata.NFFT == 5*n && ...
        metadata.InputLength == n && isequal(metadata.MeanRemoved,true) && ...
        strcmp(metadata.FrequencyCoordinate,'cycles per coordinate unit');
end
requiredRender = {'PowerSpectrumMethod','PowerSpectrumTimeBandwidth', ...
    'PowerSpectrumTaperCount','PowerSpectrumPaddingFactor', ...
    'PowerSpectrumNFFT','PowerSpectrumInputLength', ...
    'PowerSpectrumMeanRemoved','PowerSpectrumFrequencyCoordinate', ...
    'PowerSpectrumDisplayed','PowerSpectrumHeadroomFraction', ...
    'PowerSpectrumYLimits','PowerSpectrumYTicks','MinimumFontSizePoints'};
