function validateSettings(settings)
positiveScalars = {'LOWESSWindowKyr','PlotFrequencyMaximum','MaxFrequencyBins', ...
    'NumSurrogates','IAAFTIterations','IAAFTSpectralTolerance'};
for ii = 1:numel(positiveScalars)
    value = settings.(positiveScalars{ii});
    if ~(isnumeric(value) && isscalar(value) && isfinite(value) && value > 0)
        error('Acycle:BispectralValidation:InvalidSettings', ...
            '%s must be a positive finite scalar.',positiveScalars{ii});
    end
end
integerScalars = {'MaxFrequencyBins','NumSurrogates','IAAFTIterations','RandomSeed'};
for ii = 1:numel(integerScalars)
    value = settings.(integerScalars{ii});
    if ~(isnumeric(value) && isscalar(value) && isfinite(value) && ...
            value == round(value))
        error('Acycle:BispectralValidation:InvalidSettings', ...
            '%s must be a finite integer.',integerScalars{ii});
    end
end
if settings.NumSurrogates < 19
    error('Acycle:BispectralValidation:InvalidSettings', ...
        'NumSurrogates must be at least 19.');
end
if settings.NumSurrogates > 99999
    error('Acycle:BispectralValidation:InvalidSettings', ...
        'NumSurrogates must not exceed 99999.');
end
if settings.MaxFrequencyBins < 16
    error('Acycle:BispectralValidation:InvalidSettings', ...
        'MaxFrequencyBins must be at least 16.');
end
if settings.IAAFTSpectralTolerance > 1
    error('Acycle:BispectralValidation:InvalidSettings', ...
        'IAAFTSpectralTolerance must lie in (0,1].');
end
end

function settings = parseSettings(settings,varargin)
if isempty(varargin), return, end
if mod(numel(varargin),2) ~= 0
    error('Acycle:BispectralValidation:InvalidOptions','Use name/value pairs.');
end
names = fieldnames(settings);
for ii = 1:2:numel(varargin)
    index = find(strcmpi(char(varargin{ii}),names),1);
    if isempty(index)
        error('Acycle:BispectralValidation:UnknownOption', ...
            'Unknown option: %s',char(varargin{ii}));
    end
    settings.(names{index}) = varargin{ii+1};
end
end
