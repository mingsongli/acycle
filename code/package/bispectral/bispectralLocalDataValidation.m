function cutoff = expectedRetainCutoff(result,quantity,fraction,minimum,maximum)
f = result.Frequency(:);
[f1,f2] = meshgrid(f,f);
visible = f1 >= minimum & f1 <= maximum & f2 >= minimum & f2 <= maximum;
switch quantity
    case 'bispectrum-magnitude'
        raw = result.BispectrumMagnitude;
        finitePositive = raw(isfinite(raw) & raw > 0);
        if isempty(finitePositive)
            floorValue = realmin;
        else
            floorValue = max(realmin,min(finitePositive)*0.1);
        end
        metric = nan(size(raw));
        valid = isfinite(raw);
        metric(valid) = log10(max(raw(valid),floorValue));
    case 'bicoherence-squared'
        metric = result.BicoherenceSquared;
    otherwise
        error('Acycle:BispectralValidation:OverviewRetain', ...
            'Unknown retain metric: %s',quantity);
end
if fraction >= 1
    cutoff = -Inf;
    return
end
values = sort(metric(isfinite(metric) & visible));
if isempty(values)
    cutoff = -Inf;
    return
end
firstKept = max(1,min(numel(values),floor((1-fraction)*numel(values))+1));
cutoff = values(firstKept);
end

function same = numericVectorsClose(first,second)
first = double(first(:));
second = double(second(:));
if ~isequal(size(first),size(second)) || ...
        ~isequal(isnan(first),isnan(second)) || ...
        ~isequal(isinf(first),isinf(second))
    same = false;
    return
end
if ~all(first(isinf(first)) == second(isinf(second)))
    same = false;
    return
end
finite = isfinite(first) & isfinite(second);
scale = max([1;abs(first(finite));abs(second(finite))]);
same = all(abs(first(finite)-second(finite)) <= 512*eps(scale));
end

function same = numericScalarsClose(first,second)
same = numericVectorsClose(first,second);
end

