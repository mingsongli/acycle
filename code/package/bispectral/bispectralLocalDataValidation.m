function validation = bispectralLocalDataValidation(outputParent,varargin)
%BISPECTRALLOCALDATAVALIDATION Reproducible LR04/CENOGRID study.
%   VALIDATION = BISPECTRALLOCALDATAVALIDATION(OUTPUTPARENT) analyzes
%   the local LR04 stack and three five-million-year CENOGRID intervals.
%   Each record is evaluated both before and after an explicitly documented
%   800 kyr LOWESS trend removal. Every selected record is explicitly rebuilt
%   on its interval-specific median-spacing grid before strict FFT analysis.
%   The bundled files in data/Examples are used by default. LR04File,
%   CenogridFile, LOWESSWindowKyr, PlotFrequencyMaximum, MaxFrequencyBins,
%   NumSurrogates, IAAFTIterations, IAAFTSpectralTolerance, and RandomSeed
%   can be overridden with name/value pairs. The formal defaults use 999
%   accepted IAAFT surrogates and at most 1024 computed frequency-axis bins.

toolboxDirectory = fileparts(mfilename('fullpath'));
repositoryRoot = fileparts(fileparts(fileparts(toolboxDirectory)));
settings = struct( ...
    'LR04File',fullfile(repositoryRoot,'data','Examples','LR04stack5320ka.txt'), ...
    'CenogridFile',fullfile(repositoryRoot,'data','Examples', ...
        'Example-cenogrid-d18o.txt'), ...
    'LOWESSWindowKyr',800, ...
    'PlotFrequencyMaximum',0.10, ...
    'MaxFrequencyBins',1024, ...
    'NumSurrogates',999, ...
    'IAAFTIterations',200, ...
    'IAAFTSpectralTolerance',0.02, ...
    'RandomSeed',20260802);
settings = parseSettings(settings,varargin{:});
validateSettings(settings);

if nargin < 1 || isempty(outputParent)
    error('Acycle:BispectralValidation:MissingOutput', ...
        'An output parent directory is required.');
end
if ~isfile(settings.LR04File)
    error('Acycle:BispectralValidation:MissingLR04','Missing file: %s',settings.LR04File);
end
if ~isfile(settings.CenogridFile)
    error('Acycle:BispectralValidation:MissingCenogrid', ...
        'Missing file: %s',settings.CenogridFile);
end
if ~isfolder(outputParent)
    [ok,message] = mkdir(outputParent);
    if ~ok, error('Acycle:BispectralValidation:CreateOutput','%s',message); end
end

outputDirectory = createUniqueValidationDirectory(outputParent);

lr04 = readTwoColumn(settings.LR04File);
cenogrid = readTwoColumn(settings.CenogridFile);
definitions = struct( ...
    'Name',{'LR04_0-5.32Ma','CENOGRID_0-5Ma','CENOGRID_10-15Ma','CENOGRID_50-55Ma'}, ...
    'Source',{'lr04','cenogrid','cenogrid','cenogrid'}, ...
    'StartKyr',{0,0,10000,50000}, ...
    'EndKyr',{5320,5000,15000,55000});

rows = repmat(emptySummaryRow(),numel(definitions),1);
caseFiles = cell(numel(definitions),1);
allSignificantTriads = table();
allComputedSignificantTriads = table();
tag = lowessTag(settings.LOWESSWindowKyr);
for caseIndex = 1:numel(definitions)
    definition = definitions(caseIndex);
    if strcmp(definition.Source,'lr04')
        sourceData = lr04;
        sourceFile = settings.LR04File;
    else
        sourceData = cenogrid;
        sourceFile = settings.CenogridFile;
    end
    selected = sourceData(sourceData(:,1) >= definition.StartKyr & ...
        sourceData(:,1) <= definition.EndKyr,:);
    if size(selected,1) < 32
        error('Acycle:BispectralValidation:TooShort', ...
            '%s contains fewer than 32 observations.',definition.Name);
    end
    fprintf('\n[%d/%d] %s: preparing %d observations\n', ...
        caseIndex,numel(definitions),definition.Name,size(selected,1));
    [regular,regularization] = prepareRegularSeries(selected);
    [detrended,trend,lowessSamples,effectiveLowessKyr] = ...
        removeLowessTrend(regular,settings.LOWESSWindowKyr);
    external = externalPreprocessingMetadata(regularization, ...
        settings.LOWESSWindowKyr,lowessSamples,effectiveLowessKyr);
    caseSettings = settings;
    caseSettings.RandomSeed = settings.RandomSeed+caseIndex-1;

    caseDirectory = fullfile(outputDirectory,definition.Name);
    [ok,message] = mkdir(caseDirectory);
    if ~ok, error('Acycle:BispectralValidation:CreateCaseOutput','%s',message); end
    trendVariable = matlab.lang.makeValidName([tag,'Trend']);
    inputTable = table(regular(:,1),regular(:,2),trend,detrended(:,2), ...
        'VariableNames',{'AgeKyr','RegularizedValue',trendVariable,'DetrendedValue'});
    writetable(inputTable,fullfile(caseDirectory,'analysis-inputs.csv'));

    rawOptions = studyOptions(regular,definition.Name,caseSettings,'none');
    fprintf('  raw/regularized estimate ...\n');
    rawResult = bispectralAnalyze(regular,rawOptions);
    rawResult.ExternalPreprocessing = external;
    rawResult.ExternalPreprocessing.Role = 'regularized raw sensitivity control';
    rawResult.ExternalPreprocessing.LOWESS.AppliedToResult = false;
    detrendedOptions = studyOptions(detrended, ...
        [definition.Name,'_',tag],caseSettings,'surrogate-global');
    fprintf('  LOWESS-detrended estimate with %d IAAFT max-stat surrogates ...\n', ...
        settings.NumSurrogates);
    detrendedResult = bispectralAnalyze(detrended,detrendedOptions);
    detrendedResult.ExternalPreprocessing = external;
    detrendedResult.ExternalPreprocessing.Role = ...
        'primary LOWESS-detrended sensitivity result';
    detrendedResult.ExternalPreprocessing.LOWESS.AppliedToResult = true;

    validateResult(rawResult,settings.PlotFrequencyMaximum,caseSettings,false);
    validateResult(detrendedResult,settings.PlotFrequencyMaximum,caseSettings,true);
    if ~isequal(rawResult.Frequency,detrendedResult.Frequency) || ...
            ~isequal(rawResult.PrincipalDomainMask,detrendedResult.PrincipalDomainMask)
        error('Acycle:BispectralValidation:InconsistentGrid', ...
            '%s raw and detrended results do not share a computed grid.',definition.Name);
    end

    fprintf('  rendering and saving validated Overview figures ...\n');
    [rawFiles,rawOverviewQA] = saveOverviewResult(rawResult,caseDirectory, ...
        [definition.Name,'_raw']);
    [detrendedFiles,detrendedOverviewQA] = saveOverviewResult( ...
        detrendedResult,caseDirectory,[definition.Name,'_',tag]);
    trendFiles = saveTrendFigure(regular,trend,detrended,caseDirectory, ...
        definition.Name,tag,settings.LOWESSWindowKyr);

    rawPeak = peakSummary(rawResult,settings.PlotFrequencyMaximum,false);
    detrendedPeak = peakSummary(detrendedResult,settings.PlotFrequencyMaximum,true);
    significantTriads = significantTriadTable( ...
        detrendedResult,settings.PlotFrequencyMaximum,definition.Name);
    computedSignificantTriads = significantTriadTable( ...
        detrendedResult,Inf,definition.Name);
    significantTriadPath = fullfile(caseDirectory,'significant-visible-triads.csv');
    computedTriadPath = fullfile(caseDirectory,'significant-computed-triads.csv');
    writetable(significantTriads,significantTriadPath);
    writetable(computedSignificantTriads,computedTriadPath);
    if isempty(allSignificantTriads)
        allSignificantTriads = significantTriads;
    else
        allSignificantTriads = [allSignificantTriads;significantTriads]; %#ok<AGROW>
    end
    if isempty(allComputedSignificantTriads)
        allComputedSignificantTriads = computedSignificantTriads;
    else
        allComputedSignificantTriads = [allComputedSignificantTriads; ...
            computedSignificantTriads]; %#ok<AGROW>
    end
    rows(caseIndex) = struct( ...
        'Case',string(definition.Name), ...
        'SourceFile',string(sourceFile), ...
        'StartKyr',regular(1,1), ...
        'EndKyr',regular(end,1), ...
        'OriginalN',regularization.OriginalCount, ...
        'RegularN',size(regular,1), ...
        'SampleIntervalKyr',regularization.SampleInterval, ...
        'OriginalMaxSpacingDeparturePercent', ...
            100*regularization.RelativeSpacingDeparture, ...
        'LargestGapFactor',regularization.LargestGapFactor, ...
        'OriginallyIrregular',regularization.OriginallyIrregular, ...
        'RegularGridReconstructed',regularization.RegularGridReconstructed, ...
        'LOWESSSamples',lowessSamples, ...
        'EffectiveLOWESSWindowKyr',effectiveLowessKyr, ...
        'RawLongPeriodPowerFraction',longPeriodPowerFraction( ...
            regular(:,2),regularization.SampleInterval,settings.LOWESSWindowKyr), ...
        'DetrendedLongPeriodPowerFraction',longPeriodPowerFraction( ...
            detrended(:,2),regularization.SampleInterval,settings.LOWESSWindowKyr), ...
        'RawPeakBicoherenceSquared',rawPeak.BicoherenceSquared, ...
        'RawPeakF1PerKyr',rawPeak.F1, ...
        'RawPeakF2PerKyr',rawPeak.F2, ...
        'DetrendedPeakBicoherenceSquared',detrendedPeak.BicoherenceSquared, ...
        'DetrendedPeakF1PerKyr',detrendedPeak.F1, ...
        'DetrendedPeakF2PerKyr',detrendedPeak.F2, ...
        'DetrendedSignificantVisibleTriads',detrendedPeak.SignificantCount, ...
        'DetrendedSignificantComputedTriads',height(computedSignificantTriads), ...
        'GlobalSurrogateThreshold',detrendedResult.Significance.Threshold, ...
        'ThresholdComparison',string( ...
            detrendedResult.Significance.ThresholdComparison), ...
        'InferenceMethod',"IAAFT maximum-statistic FWER", ...
        'FWERConfidenceLevel',detrendedResult.Significance.ConfidenceLevel, ...
        'InferenceFamily',string( ...
            detrendedResult.Significance.InferenceFamilyDefinition), ...
        'InferenceFamilyTriadCount', ...
            detrendedResult.Significance.InferenceFamilyTriadCount, ...
        'ComputedAxisBinCount',detrendedResult.Meta.ComputedAxisBinCount, ...
        'FrequencyBinStride',detrendedResult.Meta.FrequencyBinStride, ...
        'RayleighResolutionPerKyr',detrendedResult.Meta.RayleighResolution, ...
        'ComputedAxisFrequencyMinimumPerKyr', ...
            detrendedResult.Meta.ComputedAxisFrequencyMinimum, ...
        'ComputedAxisFrequencyMaximumPerKyr', ...
            detrendedResult.Meta.ComputedAxisFrequencyMaximum, ...
        'SurrogateType',string(detrendedResult.Significance.SurrogateType), ...
        'AcceptedSurrogates',detrendedResult.Significance.NumSurrogates, ...
        'IAAFTIterations',detrendedResult.Options.IAAFTIterations, ...
        'IAAFTSpectralTolerance', ...
            detrendedResult.Significance.IAAFTSpectralTolerance, ...
        'SurrogateAttempts',detrendedResult.Significance.SurrogateAttemptCount, ...
        'RejectedSurrogates',detrendedResult.Significance.RejectedSurrogateCount, ...
        'RandomSeed',detrendedResult.Significance.RandomSeed, ...
        'MaximumAcceptedIAAFTSpectralError',max( ...
            detrendedResult.Significance.SurrogateSpectralErrors,[],'omitnan'));
    caseFiles{caseIndex} = struct('Raw',rawFiles,'Primary',detrendedFiles, ...
        'RawOverviewQA',rawOverviewQA,'PrimaryOverviewQA',detrendedOverviewQA, ...
        'Trend',trendFiles,'VisibleSignificantTriads',significantTriadPath, ...
        'ComputedSignificantTriads',computedTriadPath);
    fprintf('  complete: raw long-period fraction %.4f -> detrended %.4f\n', ...
        rows(caseIndex).RawLongPeriodPowerFraction, ...
        rows(caseIndex).DetrendedLongPeriodPowerFraction);
end

summary = struct2table(rows);
writetable(summary,fullfile(outputDirectory,'validation-summary.csv'));
writetable(allSignificantTriads,fullfile(outputDirectory,'significant-visible-triads.csv'));
writetable(allComputedSignificantTriads, ...
    fullfile(outputDirectory,'significant-computed-triads.csv'));
writeStudyNotes(fullfile(outputDirectory,'README.md'),summary,settings);
validation = struct( ...
    'Passed',true, ...
    'OutputDirectory',outputDirectory, ...
    'Created',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
    'Settings',settings, ...
    'Summary',summary, ...
    'CaseFiles',{caseFiles});
save(fullfile(outputDirectory,'validation-workspace.mat'),'validation','-v7.3');
jsonSummary = struct('Passed',validation.Passed,'Created',validation.Created, ...
    'OutputDirectory',outputDirectory,'Settings',settings, ...
    'Summary',table2struct(summary));
writeText(fullfile(outputDirectory,'validation-summary.json'), ...
    [jsonencode(jsonSummary,'PrettyPrint',true),newline]);
fprintf('\nValidation output: %s\n',outputDirectory);
end

function triads = significantTriadTable(result,plotMaximum,caseName)
f = result.Frequency(:);
[f1Grid,f2Grid] = meshgrid(f,f);
mask = result.SignificantMask & f1Grid <= plotMaximum & f2Grid <= plotMaximum;
indices = find(mask);
[~,order] = sort(result.BicoherenceSquared(indices),'descend');
indices = indices(order);
[row,column] = ind2sub(size(mask),indices);
f1 = f(column);
f2 = f(row);
f3 = f1+f2;
triads = table(repmat(string(caseName),numel(indices),1),f1,f2,f3, ...
    1./f1,1./f2,1./f3,result.BicoherenceSquared(indices), ...
    result.Significance.PValue(indices),result.BispectrumMagnitude(indices), ...
    'VariableNames',{'Case','F1PerKyr','F2PerKyr','F3PerKyr', ...
    'Period1Kyr','Period2Kyr','Period3Kyr','BicoherenceSquared', ...
    'GlobalPValue','BispectrumMagnitude'});
end

