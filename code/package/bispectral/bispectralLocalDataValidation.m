function validateResult(result,plotMaximum,settings,requireFormalInference)
finiteBicoherence = result.BicoherenceSquared(isfinite(result.BicoherenceSquared));
if isempty(finiteBicoherence) || any(finiteBicoherence < -1e-12 | ...
        finiteBicoherence > 1+1e-12)
    error('Acycle:BispectralValidation:BicoherenceBounds', ...
        'A result failed the bicoherence [0,1] bound check.');
end
if result.Meta.ComputedAxisFrequencyMaximum <= plotMaximum
    error('Acycle:BispectralValidation:FrequencyLimitCheck', ...
        'The test requires a plot maximum below the computed maximum.');
end
if result.Meta.TriadCount ~= nnz(result.PrincipalDomainMask)
    error('Acycle:BispectralValidation:TriadCount', ...
        'Stored triad count disagrees with the principal-domain mask.');
end
method = strtrim(char(result.Significance.Method));
if any(strcmpi(method,{'surrogate-global','global-surrogate','max-surrogate'})) && ...
        (result.Significance.InferenceFamilyTriadCount ~= nnz(result.ValidMask) || ...
        ~contains(result.Significance.InferenceFamilyDefinition,'Fixed finite'))
    error('Acycle:BispectralValidation:InferenceFamily', ...
        ['The saved formal result does not describe the fixed finite ', ...
         'computed-principal-domain inference family.']);
end
if requireFormalInference
    validateFormalInference(result,settings);
end
end

function validateFormalInference(result,settings)
significance = result.Significance;
required = {'Method','SurrogateType','NumSurrogates','ConfidenceLevel', ...
    'Threshold','ThresholdComparison','ThresholdMatrix','PValue', ...
    'SurrogateMaxima','SurrogateSpectralErrors','SurrogateAttemptCount', ...
    'RejectedSurrogateCount','IAAFTSpectralTolerance','RandomSeed', ...
    'InferenceFamilyTriadCount','FrequencyViewLimitsAffectInferenceFamily'};
if ~all(isfield(significance,required))
    error('Acycle:BispectralValidation:FormalInferenceQA', ...
        'The formal result is missing required IAAFT/FWER audit fields.');
end
expectedCount = settings.NumSurrogates;
tolerance = settings.IAAFTSpectralTolerance;
maxima = significance.SurrogateMaxima(:);
spectralErrors = significance.SurrogateSpectralErrors(:);
family = result.ValidMask & isfinite(result.BicoherenceSquared);
thresholdValues = significance.ThresholdMatrix(family);
familyPValues = significance.PValue(family);
alpha = 1-significance.ConfidenceLevel;
admissibleCounts = find((1+(0:expectedCount))/(expectedCount+1) <= alpha)-1;
expectedThreshold = NaN;
if ~isempty(admissibleCounts) && numel(maxima) == expectedCount
    criticalRank = expectedCount-max(admissibleCounts);
    sortedMaxima = sort(maxima);
    expectedThreshold = sortedMaxima(criticalRank);
end
confidenceTolerance = 64*eps(max(1,abs(significance.ConfidenceLevel)));
spectralTolerance = tolerance+64*eps(max(1,abs(tolerance)));
valid = strcmpi(significance.Method,'surrogate-global') && ...
    strcmpi(significance.SurrogateType,'iaaft') && ...
    significance.NumSurrogates == expectedCount && ...
    significance.RandomSeed == settings.RandomSeed && ...
    result.Options.IAAFTIterations == settings.IAAFTIterations && ...
    abs(significance.ConfidenceLevel-0.95) <= confidenceTolerance && ...
    isfinite(significance.Threshold) && ...
    significance.Threshold == expectedThreshold && ...
    contains(significance.ThresholdComparison,'strictly greater', ...
    'IgnoreCase',true) && ...
    numel(maxima) == expectedCount && all(isfinite(maxima)) && ...
    numel(spectralErrors) == expectedCount && all(isfinite(spectralErrors)) && ...
    all(spectralErrors <= spectralTolerance) && ...
    significance.IAAFTSpectralTolerance == tolerance && ...
    significance.SurrogateAttemptCount == expectedCount+ ...
    significance.RejectedSurrogateCount && ...
    significance.InferenceFamilyTriadCount == nnz(family) && ...
    ~significance.FrequencyViewLimitsAffectInferenceFamily && ...
    numel(thresholdValues) == nnz(family) && ...
    all(isfinite(thresholdValues)) && ...
    all(thresholdValues == significance.Threshold) && ...
    ~any(isfinite(significance.ThresholdMatrix(~family))) && ...
    all(isfinite(familyPValues)) && ...
    isequal(result.SignificantMask, ...
    family & result.BicoherenceSquared > significance.Threshold & ...
    significance.PValue <= alpha);
if ~valid
    error('Acycle:BispectralValidation:FormalInferenceQA', ...
        ['The primary result failed an accepted-count, IAAFT quality, ', ...
         'plus-one threshold, fixed-family, or FWER metadata assertion.']);
end
end

