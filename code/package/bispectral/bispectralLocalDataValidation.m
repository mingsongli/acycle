function fraction = longPeriodPowerFraction(y,dt,cutoffPeriod)
y = double(y(:))-mean(y,'omitnan');
nfft = 2^nextpow2(numel(y));
spectrum = fft(y,nfft);
power = abs(spectrum(2:floor(nfft/2)+1)).^2;
frequency = (1:floor(nfft/2))'/(nfft*dt);
total = sum(power);
if total <= 0
    fraction = NaN;
else
    fraction = sum(power(frequency <= 1/cutoffPeriod))/total;
end
end

