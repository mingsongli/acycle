function distance = circularDistance(a,b)
distance = abs(angle(exp(1i*(a-b))));
end

function require(condition,message)
if ~condition
    error('Acycle:Bispectral:SelfTestFailure','%s',message);
end
end

function requireThrows(action,expectedIdentifier,message)
didThrowExpected = false;
try
    action();
catch exception
    didThrowExpected = strcmp(exception.identifier,expectedIdentifier);
end
if ~didThrowExpected
    error('Acycle:Bispectral:SelfTestFailure','%s',message);
end
end
